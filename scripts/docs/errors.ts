import { ERROR_CODES, EXIT_CODES, type ErrorCategory, type ErrorSpec } from "../../packages/contract/src/errors.ts";

const CATEGORY_LABEL: Record<ErrorCategory, string> = {
  internal: "internal",
  usage: "usage",
  gated: "gated (needs an explicit write or a person)",
  auth: "auth",
  not_found: "not found",
  offline: "offline / network",
  upstream: "Stud.IP error",
  workspace: "workspace",
};

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** docs/ERRORS.md, generated from @imstudium/contract's error table. */
export function renderErrorsDoc(): string {
  const entries = Object.entries(ERROR_CODES) as Array<[string, ErrorSpec]>;
  const lines = [
    "# Errors and exit codes",
    "",
    "<!-- Generated by `bun run docs` from packages/contract/src/errors.ts. Do not edit by hand. -->",
    "",
    "Every ImStudium failure has one stable `code`. The CLI exits with the code's exit status; under `--json` it writes one error document to **stderr** (stdout stays empty). The MCP server returns the same document with `isError: true`.",
    "",
    "```json",
    '{ "error": { "code": "AUTH_REQUIRED", "message": "…", "hint": "Run: imstudium login", "retryable": false, "exitCode": 4, "status": 401 } }',
    "```",
    "",
    "- `status` is present when Stud.IP answered with an HTTP status.",
    "- `retryable` is true when the same call may succeed later unchanged (network, HTTP 429/5xx).",
    "- `details` carries machine-readable extras, e.g. `details.upstream.code` (Stud.IP's own error code) or `details.candidates` (`COURSE_AMBIGUOUS`).",
    "- `legacyCode` names the pre-0.3 code when an old alias was thrown; it disappears in a later minor.",
    "",
    "## Exit codes",
    "",
    "| Exit | Category |",
    "|---|---|",
    ...Object.entries(EXIT_CODES).map(([cat, exit]) => `| ${exit} | ${cat === "ok" ? "success" : CATEGORY_LABEL[cat as ErrorCategory]} |`),
    "",
    "## Codes",
    "",
    "| Code | Exit | Retryable | When | Default hint |",
    "|---|---|---|---|---|",
    ...entries.map(
      ([code, s]) => `| \`${code}\` | ${EXIT_CODES[s.category]} | ${s.retryable ? "yes" : "no"} | ${cell(s.summary)} | ${cell(s.hint)} |`,
    ),
    "",
    "## Legacy aliases",
    "",
    "Older codes are mapped on the way out, so scripts written for 0.2 see the new code plus `legacyCode`.",
    "",
    "| Old code | Now |",
    "|---|---|",
    ...entries.flatMap(([code, s]) => (s.aliases ?? []).map((a) => `| \`${a}\` | \`${code}\` |`)),
    "",
  ];
  return lines.join("\n");
}
