import type { Argument, Command, Option } from "commander";
import { buildProgram, HELP_GROUPS } from "../../packages/cli/src/program.ts";
import { CLI_OUTPUTS, toJsonSchema } from "../../packages/contract/src/index.ts";

/**
 * docs/COMMANDS.md from the Commander tree (names, arguments, options,
 * defaults, descriptions) and @imstudium/contract (the --json shape). The
 * help text and the doc cannot drift: both come from the same objects.
 */

type JsonSchema = {
  type?: string | string[];
  anyOf?: JsonSchema[];
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  description?: string;
  const?: unknown;
  enum?: unknown[];
};

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function typeOf(node: JsonSchema | undefined): string {
  if (!node) return "any";
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((e) => JSON.stringify(e)).join(" \\| ");
  if (node.anyOf) return [...new Set(node.anyOf.map(typeOf))].join(" \\| ");
  const t = Array.isArray(node.type) ? node.type.join(" \\| ") : node.type;
  if (t === "array") return `${typeOf(node.items)}[]`;
  return t ?? "any";
}

function keysTable(schema: JsonSchema): string[] {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  return [
    "| Key | Type | |",
    "|---|---|---|",
    ...Object.entries(props).map(([k, v]) => `| \`${k}\`${required.has(k) ? "" : "?"} | ${typeOf(v)} | ${esc(v.description ?? "")} |`),
  ];
}

function outputSection(path: string): string[] {
  if (!(path in CLI_OUTPUTS)) return [];
  const schema = toJsonSchema(path) as JsonSchema | null;
  if (!schema) return [];
  const lines = ["", `**\`--json\`** — full JSON Schema: \`imstudium schema ${path}\``, ""];
  if (schema.anyOf) {
    schema.anyOf.forEach((variant, i) => {
      lines.push(`Shape ${i + 1} of ${schema.anyOf!.length}:`, "", ...keysTable(variant), "");
    });
    lines.pop();
  } else {
    lines.push(...keysTable(schema));
  }
  return lines;
}

function argLabel(a: Argument): string {
  const name = `${a.name()}${a.variadic ? "..." : ""}`;
  return a.required ? `<${name}>` : `[${name}]`;
}

function optionRow(o: Option): string {
  const def = o.defaultValue !== undefined && o.defaultValue !== false ? ` (default: \`${String(o.defaultValue)}\`)` : "";
  return `| \`${o.flags.replace(/\|/g, "\\|")}\` | ${esc(o.description ?? "")}${def} |`;
}

function commandPath(cmd: Command): string[] {
  const parts: string[] = [];
  for (let c: Command | null = cmd; c && c.parent; c = c.parent) parts.unshift(c.name());
  return parts;
}

function renderCommand(cmd: Command, depth: number): string[] {
  const path = commandPath(cmd);
  const args = (cmd.registeredArguments ?? []) as readonly Argument[];
  const options = cmd.options.filter((o) => !o.hidden);
  const aliases = cmd.aliases();
  const lines = [
    `${"#".repeat(depth)} \`imstudium ${path.join(" ")}\``,
    "",
    cmd.description(),
    "",
    "```",
    `imstudium ${path.join(" ")}${cmd.commands.length ? " <command>" : ""}${args.length ? ` ${args.map(argLabel).join(" ")}` : ""}${options.length ? " [options]" : ""}`,
    "```",
  ];
  if (aliases.length) lines.push("", `Alias: ${aliases.map((a) => `\`${a}\``).join(", ")}`);
  if (args.length) {
    lines.push("", "| Argument | |", "|---|---|", ...args.map((a) => `| \`${argLabel(a)}\` | ${esc(a.description ?? "")} |`));
  }
  if (options.length) lines.push("", "| Option | |", "|---|---|", ...options.map(optionRow));
  lines.push(...outputSection(path.join(" ")));
  lines.push("");
  for (const sub of cmd.commands) lines.push(...renderCommand(sub, depth + 1));
  return lines;
}

export function renderCommandsDoc(): string {
  const program = buildProgram();
  const byName = new Map(program.commands.map((c) => [c.name(), c]));
  const lines = [
    "# Command reference",
    "",
    "<!-- Generated by `bun run docs` from the Commander tree (packages/cli/src/program.ts) and @imstudium/contract. Do not edit by hand. -->",
    "",
    "Every command accepts the global options. With `--json` a command prints exactly one JSON document on stdout (`schemaVersion: \"1\"` plus the keys below); errors go to stderr as one JSON document with a stable `code` and the process exit code ([ERRORS.md](ERRORS.md)). Keys may be added in a minor release; removing or retyping one is a breaking change.",
    "",
    "| Global option | |",
    "|---|---|",
    ...program.options.filter((o) => !o.hidden).map(optionRow),
    "",
    "Shared flags mean the same everywhere: `-o, --output <dir>` is the Studium workspace (or, on `files download` and `--save`, the write destination), `-n, --limit <n>` cuts a list (a positive whole number), `--since <when>` takes `24h`, `7d`, `2w`, `today` or a date, `--course <name>` takes a title fragment, shortcut, slug, number or id.",
    "",
    "## Contents",
    "",
    ...HELP_GROUPS.map(
      (g) => `- **${g.title}:** ${g.commands.filter((n) => byName.has(n)).map((n) => `[\`${n}\`](#imstudium-${n})`).join(" · ")}`,
    ),
    "",
  ];
  for (const g of HELP_GROUPS) {
    lines.push(`## ${g.title}`, "");
    for (const name of g.commands) {
      const cmd = byName.get(name);
      if (cmd) lines.push(...renderCommand(cmd, 3));
    }
  }
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
